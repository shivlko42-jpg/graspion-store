let currentGraspionLang = 'en';

function graspionT(key) {
  return (GRASPION_TRANSLATIONS[currentGraspionLang] && GRASPION_TRANSLATIONS[currentGraspionLang][key]) || GRASPION_TRANSLATIONS.en[key] || key;
}

function setGraspionLanguage(lang) {
  currentGraspionLang = lang;
  applyGraspionTranslations();
  document.dispatchEvent(new CustomEvent('graspionLanguageChanged', { detail: { lang: lang } }));
}

function applyGraspionTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    const key = el.getAttribute('data-i18n');
    el.textContent = graspionT(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = graspionT(key);
  });
}

function renderLanguageSwitcher(elementId) {
  const el = document.getElementById(elementId);
  if (!el) return;
  el.innerHTML =
    '<select id="graspionLangSwitcher" style="font-size:11px; font-weight:700; padding:6px 10px; border-radius:8px; border:1px solid #e5e7eb; background:#fff; cursor:pointer;">' +
      '<option value="en">🇬🇧 English</option>' +
      '<option value="hi">🇮🇳 हिंदी</option>' +
    '</select>';
  document.getElementById('graspionLangSwitcher').value = currentGraspionLang;
  document.getElementById('graspionLangSwitcher').addEventListener('change', function(e) {
    setGraspionLanguage(e.target.value);
  });
}

document.addEventListener('DOMContentLoaded', function() {
  applyGraspionTranslations();
});
